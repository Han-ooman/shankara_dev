if (!function_exists('sync_status_tabel')) {
    /**
     * Ringkasan jumlah baris di kedua sisi + waktu sinkron terakhir.
     */
    function sync_status_tabel(sdb $offline, sdb $online, array $tabel): array {
        $pdoOff = $offline->getPDO();
        $pdoOn  = $online->getPDO();
        $state  = sync_ambil_state($offline, $online);

        $out = [];
        foreach ($tabel as $t) {
            $row = [
                'tabel'     => $t,
                'label'     => sync_label_tabel($t),
                'offline'   => 0,
                'online'    => 0,
                'push_at'   => null,
                'pull_at'   => null,
                'ada'       => true,
            ];
            if ($pdoOff) {
                try { $row['offline'] = (int)$pdoOff->query('SELECT COUNT(*) FROM ' . sync_quote('mysql', $t))->fetchColumn(); }
                catch (Throwable $e) { $row['ada'] = false; }
            }
            if ($pdoOn) {
                try { $row['online'] = (int)$pdoOn->query('SELECT COUNT(*) FROM ' . sync_quote('pgsql', $t))->fetchColumn(); }
                catch (Throwable $e) { $row['ada'] = false; }
            }
            $row['push_at'] = $state['push'][$t] ?? null;
            $row['pull_at'] = $state['pull'][$t] ?? null;
            $out[] = $row;
        }
        return $out;
    }
}

if (!function_exists('sync_ambil_state')) {
    /** Ambil map waktu sinkron terakhir: ['push'=>[tabel=>waktu], 'pull'=>[tabel=>waktu]] */
    function sync_ambil_state(sdb $offline, sdb $online): array {
        $out = ['push' => [], 'pull' => []];
        $ambil = function (sdb $c, string $arah) use (&$out) {
            $pdo = $c->getPDO();
            if (!$pdo) return;
            try {
                $ada = (int)$pdo->query('SELECT COUNT(*) FROM ' . sync_quote($c->getDriver(), 'sync_state'))->fetchColumn();
            } catch (Throwable $e) {
                return;
            }
            if (!$ada) return;
            try {
                $st = $pdo->prepare('SELECT tabel, last_sync_at FROM ' . sync_quote($c->getDriver(), 'sync_state') . ' WHERE arah = ?');
                $st->execute([$arah]);
                foreach ($st->fetchAll(PDO::FETCH_ASSOC) as $r) {
                    $out[$arah][$r['tabel']] = $r['last_sync_at'];
                }
            } catch (Throwable $e) {
                // abaikan
            }
        };
        $ambil($online, 'push');   // online menerima push
        $ambil($offline, 'pull');  // offline menerima pull
        return $out;
    }
}

if (!function_exists('sync_riwayat')) {
    /** Riwayat sinkronisasi terakhir (dari sisi operator/offline). */
    function sync_riwayat(sdb $log, int $limit = 25): array {
        $pdo = $log->getPDO();
        if (!$pdo) return [];
        try {
            $ada = (int)$pdo->query('SELECT COUNT(*) FROM ' . sync_quote($log->getDriver(), 'sync_log'))->fetchColumn();
            if (!$ada) return [];
        } catch (Throwable $e) {
            return [];
        }
        try {
            $sql = 'SELECT tabel, arah, status, rows_copied, rows_skipped, pesan, created_at FROM '
                 . sync_quote($log->getDriver(), 'sync_log') . ' ORDER BY id DESC LIMIT ' . (int)$limit;
            return $pdo->query($sql)->fetchAll(PDO::FETCH_ASSOC);
        } catch (Throwable $e) {
            return [];
        }
    }
