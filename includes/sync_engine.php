if (!function_exists('sync_perbaiki_auto_increment')) {
    /**
     * MySQL lokal: pastikan PK bertipe AUTO_INCREMENT (menyamakan perilaku
     * dengan identity di PostgreSQL) supaya INSERT tanpa id tetap jalan.
     */
    function sync_perbaiki_auto_increment(sdb $c): array {
        $pdo = $c->getPDO();
        $hasil = [];
        if (!$pdo || $c->getDriver() !== 'mysql') return $hasil;
        try {
            $st = $pdo->query("SELECT k.TABLE_NAME, k.COLUMN_NAME
                               FROM information_schema.KEY_COLUMN_USAGE k
                               JOIN information_schema.COLUMNS c
                                 ON c.TABLE_SCHEMA = k.TABLE_SCHEMA
                                AND c.TABLE_NAME = k.TABLE_NAME
                                AND c.COLUMN_NAME = k.COLUMN_NAME
                               WHERE k.TABLE_SCHEMA = DATABASE()
                                 AND k.CONSTRAINT_NAME = 'PRIMARY'
                                 AND c.EXTRA NOT LIKE '%auto_increment%'
                                 AND k.ORDINAL_POSITION = 1");
            foreach ($st->fetchAll(PDO::FETCH_ASSOC) as $row) {
                $t = $row['TABLE_NAME'];
                $col = $row['COLUMN_NAME'];
                $max = (int)$pdo->query('SELECT COALESCE(MAX(' . sync_quote('mysql', $col) . '),0) FROM ' . sync_quote('mysql', $t))->fetchColumn();
                $pdo->exec('ALTER TABLE ' . sync_quote('mysql', $t) . ' MODIFY ' . sync_quote('mysql', $col) . ' INT NOT NULL AUTO_INCREMENT');
                $pdo->exec('ALTER TABLE ' . sync_quote('mysql', $t) . ' AUTO_INCREMENT = ' . ($max + 1));
                $hasil[] = $t . '.' . $col;
            }
        } catch (Throwable $e) {
            error_log('sync: perbaiki auto_increment gagal: ' . $e->getMessage());
        }
        return $hasil;
    }
}

class SyncEngine
{
    public const POLICY_OVERWRITE = 'overwrite';
    public const POLICY_SKIP      = 'skip';
    public const POLICY_NEWEST   = 'newest';

    /** @var sdb koneksi sumber data */
    private $src;
    /** @var sdb koneksi tujuan data */
    private $dst;
    /** @var sdb koneksi pencatat riwayat (default: tujuan) */
    private $log;
    private string $arah;
    private string $policy;
    private bool $hapus;
    private bool $dry;
    private int $batch = 150;
    private array $hasil = [];

    public function __construct(
        sdb $src,
        sdb $dst,
        string $arah = 'push',
        string $policy = self::POLICY_OVERWRITE,
        bool $hapus = false,
        bool $dry = false,
        ?sdb $log = null
    ) {
        $this->src  = $src;
        $this->dst  = $dst;
        $this->log  = $log ?? $dst;
        $this->arah = ($arah === 'pull') ? 'pull' : 'push';
        $this->policy = in_array($policy, [self::POLICY_OVERWRITE, self::POLICY_SKIP, self::POLICY_NEWEST], true)
            ? $policy : self::POLICY_OVERWRITE;
        $this->hapus = $hapus;
        $this->dry   = $dry;
    }

    public function getArah(): string    { return $this->arah; }
    public function getPolicy(): string  { return $this->policy; }
    public function isDryRun(): bool     { return $this->dry; }
    public function laporan(): array     { return $this->hasil; }

    /**
     * Jalankan sinkronisasi untuk daftar tabel.
     * @param array $tabel nama tabel (base table)
     */
    public function jalankan(array $tabel): array {
        $this->hasil = [];
        foreach ($tabel as $t) {
            $t = trim((string)$t);
            if ($t === '') continue;
            $this->hasil[$t] = $this->sinkronTabel($t);
            if (!$this->dry) $this->simpanState($t, $this->hasil[$t]);
        }
        if (!$this->dry) $this->tulisRiwayat();
        return $this->hasil;
    }

    // ------------------------------------------------------------------
    // Per tabel
    // ------------------------------------------------------------------
    private function sinkronTabel(string $tabel): array {
        $r = [
            'tabel'     => $tabel,
            'label'     => sync_label_tabel($tabel),
            'arah'      => $this->arah,
            'status'    => 'ok',
            'pesan'     => '',
            'sumber'    => 0,
            'tujuan'    => 0,
            'tersalin'  => 0,
            'terinsert' => 0,
            'terupdate' => 0,
            'dilewati'  => 0,
            'dihapus'   => 0,
            'waktu'     => null,
        ];

        try {
            $pdoSrc = $this->src->getPDO();
            $pdoDst = $this->dst->getPDO();
            if (!$pdoSrc || !$pdoDst) throw new RuntimeException('Koneksi database tidak tersedia.');

            $kolSrc = $this->infoKolom($this->src, $tabel);
            $kolDst = $this->infoKolom($this->dst, $tabel);
            if (!$kolSrc || !$kolDst) {
                $r['status'] = 'skip';
                $r['pesan']  = 'Tabel tidak ditemukan di ' . (!$kolSrc ? 'sumber' : 'tujuan') . '.';
                return $r;
            }
            if (!$this->isBaseTable($this->src, $tabel) || !$this->isBaseTable($this->dst, $tabel)) {
                $r['status'] = 'skip';
                $r['pesan']  = 'Bukan tabel base (view tidak disinkronkan).';
                return $r;
            }

            $r['sumber'] = $this->hitungBaris($pdoSrc, $this->src->getDriver(), $tabel);
            $r['tujuan'] = $this->hitungBaris($pdoDst, $this->dst->getDriver(), $tabel);

            // Kolom yang ada di kedua sisi (urutan kolom tujuan)
            $kolom = [];   // key lowercase => nama kolom di tujuan
            foreach ($kolDst as $lc => $info) {
                if (isset($kolSrc[$lc])) $kolom[$lc] = $info['nama'];
            }
            if (!$kolom) {
                $r['status'] = 'skip';
                $r['pesan']  = 'Tidak ada kolom yang sama di kedua sisi.';
                return $r;
            }

            // Primary key (ambil dari tujuan, fallback ke sumber)
            $pk = $this->infoPk($this->dst, $tabel);
            if (!$pk) $pk = $this->infoPk($this->src, $tabel);
            if (!$pk) {
                $r['status'] = 'skip';
                $r['pesan']  = 'Tabel tanpa primary key.';
                return $r;
            }
            $pkLower = [];
            foreach ($pk as $c) {
                $lc = strtolower($c);
                if (!isset($kolom[$lc])) {
                    $r['status'] = 'skip';
                    $r['pesan']  = "Primary key '$c' tidak ada di daftar kolom tersinkron.";
                    return $r;
                }
                $pkLower[] = $lc;
            }
            $pkNames = array_map(fn($lc) => $kolom[$lc], $pkLower);

            // Kolom waktu untuk policy "newest"
            $waktuLc = null;
            if ($this->policy === self::POLICY_NEWEST) {
                foreach (sync_kolom_waktu_preferensi() as $w) {
                    $lc = strtolower($w);
                    if (isset($kolom[$lc])) { $waktuLc = $lc; break; }
                }
                if ($waktuLc === null) {
                    $r['pesan'] = 'Tabel tanpa kolom waktu, fallback ke overwrite.';
                }
            }
            $r['waktu'] = $waktuLc ? $kolom[$waktuLc] : null;

            // Ambil baris sumber (hanya kolom yang ada di tujuan)
            $pilih = [];
            foreach ($kolom as $lc => $namaDst) $pilih[] = $kolSrc[$lc]['nama'];
            $baris = $this->ambilBaris($pdoSrc, $this->src->getDriver(), $tabel, $pilih);

            // Peta data tujuan (untuk policy skip/newest)
            $peta = $this->petaTujuan($pdoDst, $this->dst->getDriver(), $tabel, $pkNames, $waktuLc ? $kolom[$waktuLc] : null);

            $jenisKolom = [];   // lc => nama kolom tujuan
            foreach ($kolom as $lc => $namaDst) $jenisKolom[$lc] = $namaDst;

            $drvDst = $this->dst->getDriver();
            $daftarTulis = [];
            $kunciSumber = [];

            foreach ($baris as $row) {
                $kunci = $this->kunciBaris($row, $pkLower);
                $kunciSumber[$kunci] = true;

                $sudahAda = isset($peta[$kunci]);

                // ---- policy skip ----
                if ($this->policy === self::POLICY_SKIP && $sudahAda) {
                    $r['dilewati']++;
                    continue;
                }

                // ---- policy newest ----
                if ($this->policy === self::POLICY_NEWEST && $waktuLc !== null && $sudahAda) {
                    $wSrc = $this->nilaiWaktu($row[$waktuLc] ?? null);
                    $wDst = $this->nilaiWaktu($peta[$kunci]['waktu'] ?? null);
                    if ($wDst !== null && ($wSrc === null || $wDst >= $wSrc)) {
                        $r['dilewati']++;
                        continue;
                    }
                }

                $nilai = [];
                foreach ($jenisKolom as $lc => $namaDst) {
                    $tipe = $kolDst[$lc]['tipe'];
                    $nilai[] = $this->nilaiAman($row[$lc] ?? null, $tipe, $drvDst);
                }

                $daftarTulis[] = ['kunci' => $kunci, 'nilai' => $nilai, 'baru' => !$sudahAda];
                $r['tersalin']++;
                if ($sudahAda) $r['terupdate']++; else $r['terinsert']++;
            }

            // ---- tulis ke tujuan (batch) ----
            if ($daftarTulis && !$this->dry) {
                $this->tulisBatch($tabel, $jenisKolom, $pkNames, $daftarTulis, $pdoDst);
                $this->perbaikiUrutan($tabel, $pkNames);
            }

            // ---- hapus baris yang tidak ada di sumber ----
            if ($this->hapus && !$this->dry) {
                $hapus = [];
                foreach ($peta as $kunci => $info) {
                    if (!isset($kunciSumber[$kunci])) $hapus[] = $info['pk'];
                }
                $r['dihapus'] = $this->hapusBaris($tabel, $pkNames, $hapus, $pdoDst);
            }
        } catch (Throwable $e) {
            $r['status'] = 'gagal';
            $r['pesan']  = $e->getMessage();
            error_log('sync: tabel ' . $tabel . ' gagal: ' . $e->getMessage());
        }

        return $r;
    }

    // ------------------------------------------------------------------
    // Helper: metadata
    // ------------------------------------------------------------------
    /** @return array lc => ['nama'=>, 'tipe'=>] */
    private function infoKolom(sdb $c, string $tabel): array {
        $pdo = $c->getPDO();
        if (!$pdo) return [];
        try {
            if ($c->getDriver() === 'mysql') {
                $st = $pdo->prepare("SELECT COLUMN_NAME, DATA_TYPE FROM information_schema.COLUMNS
                                     WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ?
                                     ORDER BY ORDINAL_POSITION");
            } else {
                $st = $pdo->prepare("SELECT column_name, data_type FROM information_schema.columns
                                     WHERE table_schema = 'public' AND table_name = ?
                                     ORDER BY ordinal_position");
            }
            $st->execute([$tabel]);
            $out = [];
            foreach ($st->fetchAll(PDO::FETCH_NUM) as $row) {
                $out[strtolower($row[0])] = ['nama' => $row[0], 'tipe' => $row[1]];
            }
            return $out;
        } catch (Throwable $e) {
            return [];
        }
    }

    /** True bila objek benar-benar tabel base (bukan view). */
    private function isBaseTable(sdb $c, string $tabel): bool {
        $pdo = $c->getPDO();
        if (!$pdo) return false;
        try {
            if ($c->getDriver() === 'mysql') {
                $st = $pdo->prepare("SELECT TABLE_TYPE FROM information_schema.TABLES
                                     WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ?");
            } else {
                $st = $pdo->prepare("SELECT table_type FROM information_schema.tables
                                     WHERE table_schema = 'public' AND table_name = ?");
            }
            $st->execute([$tabel]);
            $tipe = $st->fetchColumn();
            return ($tipe !== false) && strtoupper((string)$tipe) === 'BASE TABLE';
        } catch (Throwable $e) {
            return false;
        }
    }

    /** @return array nama kolom primary key */
    private function infoPk(sdb $c, string $tabel): array {
        $pdo = $c->getPDO();
        if (!$pdo) return [];
        try {
            if ($c->getDriver() === 'mysql') {
                $st = $pdo->prepare("SELECT COLUMN_NAME FROM information_schema.KEY_COLUMN_USAGE
                                     WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ?
                                       AND CONSTRAINT_NAME = 'PRIMARY'
                                     ORDER BY ORDINAL_POSITION");
                $st->execute([$tabel]);
            } else {
                $st = $pdo->prepare("SELECT a.attname FROM pg_index i
                                     JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
                                     JOIN pg_class c ON c.oid = i.indrelid
                                     WHERE c.relname = ? AND i.indisprimary
                                     ORDER BY a.attnum");
                $st->execute([$tabel]);
            }
            $out = [];
            foreach ($st->fetchAll(PDO::FETCH_NUM) as $row) $out[] = $row[0];
            return $out;
        } catch (Throwable $e) {
            return [];
        }
    }

    private function hitungBaris(PDO $pdo, string $drv, string $tabel): int {
        try {
            return (int)$pdo->query('SELECT COUNT(*) FROM ' . sync_quote($drv, $tabel))->fetchColumn();
        } catch (Throwable $e) {
            return 0;
        }
    }

    /** Ambil seluruh baris sumber, key hasil = nama kolom lowercase. */
    private function ambilBaris(PDO $pdo, string $drv, string $tabel, array $kolom): array {
        if (!$kolom) return [];
        $sql = 'SELECT ' . implode(', ', array_map(fn($c) => sync_quote($drv, $c), $kolom))
             . ' FROM ' . sync_quote($drv, $tabel);
        $st = $pdo->query($sql);
        $out = [];
        foreach ($st->fetchAll(PDO::FETCH_ASSOC) as $row) {
            $norm = [];
            foreach ($row as $k => $v) $norm[strtolower($k)] = $v;
            $out[] = $norm;
        }
        return $out;
    }

    /**
     * Peta isi tabel tujuan: kunci pk => ['pk'=>..., 'waktu'=>...].
     */
    private function petaTujuan(PDO $pdo, string $drv, string $tabel, array $pkNames, ?string $waktuName): array {
        $out = [];
        $sel = array_map(fn($c) => sync_quote($drv, $c), $pkNames);
        if ($waktuName) $sel[] = sync_quote($drv, $waktuName);
        try {
            $st = $pdo->query('SELECT ' . implode(', ', $sel) . ' FROM ' . sync_quote($drv, $tabel));
            foreach ($st->fetchAll(PDO::FETCH_ASSOC) as $row) {
                $vals = [];
                foreach ($pkNames as $pk) $vals[] = (string)($row[$pk] ?? '');
                $out[implode('||', $vals)] = [
                    'pk'    => $vals,
                    'waktu' => $waktuName ? ($row[$waktuName] ?? null) : null,
                ];
            }
        } catch (Throwable $e) {
            return [];
        }
        return $out;
    }

    private function kunciBaris(array $row, array $pkLower): string {
        $vals = [];
        foreach ($pkLower as $lc) $vals[] = (string)($row[$lc] ?? '');
        return implode('||', $vals);
    }

    // ------------------------------------------------------------------
    // Helper: tulis
    // ------------------------------------------------------------------
    /**
     * Tulis batch baris ke tujuan dengan upsert.
     * @param array $jenisKolom lc => nama kolom tujuan
     */
    private function tulisBatch(string $tabel, array $jenisKolom, array $pkNames, array $baris, PDO $pdo): void {
        $namaKolom = array_values($jenisKolom);
        $jumlah    = count($namaKolom);
        if (!$jumlah || !$baris) return;

        $batches = array_chunk($baris, $this->batch);
        foreach ($batches as $chunk) {
            $sql = $this->sqlUpsert($tabel, $namaKolom, $pkNames, count($chunk));
            $params = [];
            foreach ($chunk as $b) {
                foreach ($b['nilai'] as $v) $params[] = $v;
            }
            try {
                $st = $pdo->prepare($sql);
                $st->execute($params);
            } catch (Throwable $e) {
                // fallback: tulis satu per satu agar 1 baris rusak tidak menghentikan semua
                $satu = $this->sqlUpsert($tabel, $namaKolom, $pkNames, 1);
                foreach ($chunk as $b) {
                    try {
                        $st = $pdo->prepare($satu);
                        $st->execute($b['nilai']);
                    } catch (Throwable $e2) {
                        error_log('sync: gagal tulis ' . $tabel . ' (pk ' . $b['kunci'] . '): ' . $e2->getMessage());
                    }
                }
            }
        }
    }

    /** Bangun SQL upsert multi-row sesuai driver tujuan. */
    private function sqlUpsert(string $tabel, array $kolom, array $pkNames, int $jumlahBaris): string {
        $drv = $this->dst->getDriver();
        $q = function ($n) use ($drv) { return sync_quote($drv, $n); };

        $tempat = '(' . implode(', ', array_fill(0, count($kolom), '?')) . ')';
        $sql = 'INSERT INTO ' . $q($tabel) . ' (' . implode(', ', array_map($q, $kolom)) . ') VALUES '
             . implode(', ', array_fill(0, $jumlahBaris, $tempat));

        $upd = [];
        foreach ($kolom as $c) {
            if (in_array($c, $pkNames, true)) continue;
            $upd[] = $drv === 'mysql'
                ? $q($c) . ' = VALUES(' . $q($c) . ')'
                : $q($c) . ' = EXCLUDED.' . $q($c);
        }

        if ($drv === 'mysql') {
            if ($upd) $sql .= ' ON DUPLICATE KEY UPDATE ' . implode(', ', $upd);
        } else {
            $target = array_map($q, $pkNames);
            $sql .= ' ON CONFLICT (' . implode(', ', $target) . ') DO '
                  . ($upd ? 'UPDATE SET ' . implode(', ', $upd) : 'NOTHING');
        }
        return $sql;
    }

    /** Hapus baris tujuan yang tidak ada di sumber (opsional). */
    private function hapusBaris(string $tabel, array $pkNames, array $daftar, PDO $pdo): int {
        if (!$daftar || count($pkNames) !== 1) return 0;
        $drv = $this->dst->getDriver();
        $q = fn($n) => sync_quote($drv, $n);
        $total = 0;
        foreach (array_chunk($daftar, 200) as $chunk) {
            $vals = [];
            foreach ($chunk as $pk) $vals[] = $pk[0];
            $sql = 'DELETE FROM ' . $q($tabel) . ' WHERE ' . $q($pkNames[0]) . ' IN (' . implode(', ', array_fill(0, count($vals), '?')) . ')';
            try {
                $st = $pdo->prepare($sql);
                $st->execute($vals);
                $total += $st->rowCount();
            } catch (Throwable $e) {
                error_log('sync: gagal hapus di ' . $tabel . ': ' . $e->getMessage());
            }
        }
        return $total;
    }

    /** Samakan auto increment / sequence dengan data terbaru. */
    private function perbaikiUrutan(string $tabel, array $pkNames): void {
        if (count($pkNames) !== 1) return;
        $pdo = $this->dst->getPDO();
        if (!$pdo) return;
        $drv = $this->dst->getDriver();
        $pk  = $pkNames[0];
        try {
            $max = (int)$pdo->query('SELECT COALESCE(MAX(' . sync_quote($drv, $pk) . '), 0) FROM ' . sync_quote($drv, $tabel))->fetchColumn();
            $next = $max + 1;
            if ($drv === 'mysql') {
                $pdo->exec('ALTER TABLE ' . sync_quote('mysql', $tabel) . ' AUTO_INCREMENT = ' . $next);
            } else {
                $pdo->exec('ALTER TABLE ' . sync_quote('pgsql', $tabel) . ' ALTER COLUMN ' . sync_quote('pgsql', $pk) . ' RESTART WITH ' . $next);
            }
        } catch (Throwable $e) {
            // Kolom tanpa sequence / auto increment -> abaikan (tidak error fatal)
        }
    }

    // ------------------------------------------------------------------
    // Helper: normalisasi nilai
    // ------------------------------------------------------------------
    /**
     * Sesuaikan nilai sumber agar cocok dengan tipe kolom tujuan
     * (mis. tanggal '0000-00-00' -> NULL, angka kosong -> NULL).
     */
    private function nilaiAman($v, string $tipe, string $drv): ?string {
        if ($v === null) return null;
        if (is_bool($v)) return $v ? '1' : '0';
        if (is_int($v) || is_float($v)) return (string)$v;

        $s = (string)$v;
        $t = strtolower($tipe);

        $isAngka = in_array($t, ['integer', 'int', 'bigint', 'smallint', 'tinyint', 'mediumint',
                                 'numeric', 'decimal', 'real', 'double precision', 'money', 'float', 'double'], true)
                   || (strpos($t, 'int') !== false && strpos($t, 'interval') === false)
                   || strpos($t, 'decimal') !== false || strpos($t, 'numeric') !== false;

        $isTanggal = (strpos($t, 'date') !== false || strpos($t, 'time') !== false)
                     && strpos($t, 'timestamp with') !== false ? true
                     : (strpos($t, 'date') !== false || strpos($t, 'time') !== false);

        if ($s === '') {
            return ($isAngka || $t === 'boolean' || $t === 'bool') ? null : $s;
        }

        if ($isTanggal) {
            if (strpos($s, '0000-00-00') === 0) return null;
            if (preg_match('/^(\d{4})-(\d{2})-(\d{2})/', $s, $m)) {
                $y = (int)$m[1]; $mo = (int)$m[2]; $d = (int)$m[3];
                if ($y === 0 || $mo === 0 || $d === 0 || !checkdate($mo, $d, $y)) return null;
            }
        }

        if ($t === 'boolean' || $t === 'bool') {
            $lv = strtolower(trim($s));
            $val = in_array($lv, ['1', 't', 'true', 'yes', 'y'], true);
            return $drv === 'mysql' ? ($val ? '1' : '0') : ($val ? 'true' : 'false');
        }

        if ($isAngka && !is_numeric($s)) return null;

        return $s;
    }

    /** Ubah nilai waktu menjadi timestamp yang bisa dibandingkan. */
    private function nilaiWaktu($v): ?float {
        if ($v === null) return null;
        $s = trim((string)$v);
        if ($s === '' || strpos($s, '0000-00-00') === 0) return null;
        $ts = strtotime($s);
        return ($ts === false) ? null : (float)$ts;
    }

    // ------------------------------------------------------------------
    // Riwayat
    // ------------------------------------------------------------------
    private function tulisRiwayat(): void {
        $pdo = $this->log->getPDO();
        if (!$pdo) return;
        sync_buat_tabel_log($this->log);
        $drv = $this->log->getDriver();
        $sql = 'INSERT INTO ' . sync_quote($drv, 'sync_log')
             . ' (tabel, arah, status, rows_copied, rows_skipped, pesan)'
             . ' VALUES (?, ?, ?, ?, ?, ?)';
        try {
            $st = $pdo->prepare($sql);
            foreach ($this->hasil as $t => $r) {
                $st->execute([
                    $t,
                    $this->arah,
                    $r['status'],
                    (int)$r['tersalin'],
                    (int)$r['dilewati'],
                    mb_substr((string)$r['pesan'], 0, 500),
                ]);
            }
        } catch (Throwable $e) {
            error_log('sync: gagal menulis riwayat: ' . $e->getMessage());
        }
    }

    /** Simpan status sinkronisasi terakhir di sisi tujuan. */
    public function simpanState(string $tabel, array $r): void {
        $pdo = $this->dst->getPDO();
        if (!$pdo) return;
        sync_buat_tabel_state($this->dst);
        $drv = $this->dst->getDriver();
        $q   = fn($n) => sync_quote($drv, $n);
        $now = ($drv === 'mysql') ? 'NOW()' : 'now()';
        $err = mb_substr((string)$r['pesan'], 0, 500);

        try {
            if ($drv === 'mysql') {
                $sql = 'INSERT INTO ' . $q('sync_state') . ' (tabel, arah, last_sync_at, rows_copied, last_error)'
                     . ' VALUES (?, ?, ' . $now . ', ?, ?)'
                     . ' ON DUPLICATE KEY UPDATE last_sync_at = ' . $now
                     . ', rows_copied = VALUES(rows_copied), last_error = VALUES(last_error)';
            } else {
                $sql = 'INSERT INTO ' . $q('sync_state') . ' (tabel, arah, last_sync_at, rows_copied, last_error)'
                     . ' VALUES (?, ?, ' . $now . ', ?, ?)'
                     . ' ON CONFLICT (tabel, arah) DO UPDATE SET last_sync_at = ' . $now
                     . ', rows_copied = EXCLUDED.rows_copied, last_error = EXCLUDED.last_error';
            }
            $st = $pdo->prepare($sql);
            $st->execute([$tabel, $this->arah, (int)$r['tersalin'], $err]);
        } catch (Throwable $e) {
            error_log('sync: gagal simpan state: ' . $e->getMessage());
        }
    }
}

