<?php
// ============================================================
// ENGINE SINKRONISASI DATA DUA ARAH
//   OFFLINE : MySQL lokal (XAMPP)
//   ONLINE  : Supabase (PostgreSQL)
//
// Cara kerja: upsert berbasis primary key (id ikut tersalin).
//   MySQL : INSERT ... ON DUPLICATE KEY UPDATE
//   PG    : INSERT ... ON CONFLICT (pk) DO UPDATE SET ... = EXCLUDED...
//
// Kebijakan konflik (policy):
//   overwrite : baris tujuan ditimpa data sumber (default)
//   skip      : baris yang sudah ada di tujuan dibiarkan (aman, tanpa timpa)
//   newest    : pakai kolom waktu, data yang lebih baru menang
//               (tabel tanpa kolom waktu -> fallback overwrite)
//
// Opsi tambahan:
//   --delete-missing : baris di tujuan yang tidak ada di sumber dihapus
//   --dry-run        : hanya menghitung, tidak menulis apa pun
// ============================================================

require_once __DIR__ . '/db_adapter.php';
require_once __DIR__ . '/sync_config.php';

if (!function_exists('sync_quote')) {
    /** Quote identifier sesuai driver (backtick utk MySQL, double quote utk PG). */
    function sync_quote(string $driver, string $nama): string {
        if ($driver === 'mysql') return '`' . str_replace('`', '``', $nama) . '`';
        return '"' . str_replace('"', '""', $nama) . '"';
    }
}

if (!function_exists('sync_buat_tabel_state')) {
    /** Buat tabel sync_state di sisi yang dituju (bila belum ada). */
    function sync_buat_tabel_state(sdb $c): void {
        $pdo = $c->getPDO();
        if (!$pdo) return;
        try {
            if ($c->getDriver() === 'mysql') {
                $pdo->exec("CREATE TABLE IF NOT EXISTS sync_state (
                    id INT NOT NULL AUTO_INCREMENT,
                    tabel VARCHAR(64) NOT NULL,
                    arah VARCHAR(10) NOT NULL,
                    last_sync_at DATETIME NULL,
                    rows_copied INT NOT NULL DEFAULT 0,
                    last_error TEXT NULL,
                    PRIMARY KEY (id),
                    UNIQUE KEY sync_state_uq (tabel, arah)
                ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");
            } else {
                $pdo->exec("CREATE TABLE IF NOT EXISTS sync_state (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tabel VARCHAR(64) NOT NULL,
                    arah VARCHAR(10) NOT NULL,
                    last_sync_at TIMESTAMP NULL,
                    rows_copied INTEGER NOT NULL DEFAULT 0,
                    last_error TEXT NULL,
                    UNIQUE (tabel, arah)
                )");
            }
        } catch (Throwable $e) {
            error_log('sync: gagal membuat sync_state: ' . $e->getMessage());
        }
    }
}

